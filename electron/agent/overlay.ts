export const ROUTE_PROVIDER_ID = "diandian-openai";

/**
 * Harness plugins the SDK profile loads that 点点读书 turns off, so the model is not offered tools that can
 * only fail or that the app forbids. runtime-safety's alwaysDenied list stays as the backstop.
 */
export const DISABLED_HARNESS_PLUGINS = [
  // Office tools and skill: they need the LibreOffice engine (~300MB) the installer leaves out
  // (scripts/stage-runtime.mjs), and the app has no Office workflow.
  "office-kit",
  "tool-office",
  "skill-office",
  // Shell tools, always denied by runtime-safety; tool-pwsh is the Windows counterpart of tool-bash.
  "tool-bash",
  "tool-pwsh",
  // plugin_manager installs and toggles Harness plugins. Each call needs an approval channel the app does
  // not provide, and letting the model change the agent's own plugins is not a reading feature.
  "tool-plugin-manager",
  // The rest keep file access inside the agent's own directories (issue #55, see
  // plugins/runtime-safety/read-scope.mjs). workflow runs model-written JavaScript in a Node process whose
  // reads and network are unrestricted; working_directory moves the base that relative paths resolve
  // against; skill-filesystem pulls the skills of whoever runs the app (~/.agents/skills, ~/.dsh/skills)
  // into every request, and the app ships no skills of its own.
  "tool-workflow",
  "tool-working-directory",
  "skill-filesystem",
  "tool-skill",
] as const;

/**
 * DeepSeek Search API endpoint for web_search (issue #54), or null when the provider is not DeepSeek.
 * The Harness offers web_search only with a DeepSeek credential; 点点读书 passes the key as
 * DIANDIAN_LLM_API_KEY rather than DEEPSEEK_API_KEY, so the overlay points web-deepseek-api at it. The
 * endpoint follows the Harness rule for DeepSeek routes: the model base URL's origin plus /v1/tools.
 * Billed per successful search ($0.75 per 1,000, DeepSeek pricing as of 2026-11).
 */
export function webSearchEndpoint(settings: Pick<ModelSettings, "provider" | "baseUrl">): string | null {
  if (settings.provider !== "deepseek") return null;
  try {
    return `${new URL(settings.baseUrl).origin}/v1/tools`;
  } catch {
    return null;
  }
}

/** Where the Harness saves oversized tool output for the model to read back (an allowed read root). */
export function harnessSpillDir(dshHome: string): string {
  return path.join(dshHome, "spill");
}

/** Where the Harness keeps image attachments (dsh-attachment-local: <DSH_HOME>/attachments/v1). */
export function harnessAttachmentsDir(dshHome: string): string {
  return path.join(dshHome, "attachments");
}

/** tool-fs keeps read and read_image; its write and edit tools are always denied by runtime-safety. */
const READ_ONLY_FS_PATCH = ["- id: tool-fs", "  config:", "    write: false", "    edit: false", ""];

export interface PluginOverlayEntry {
  id: string;
  entryPath: string;
}

export interface OverlayOptions {
  dshHome: string;
  /** Legacy single-plugin field (still accepted for backwards compatibility). */
  pluginEntryPath?: string;
  /** Preferred list of Cordis plugin entry files to mount into DSH. */
  pluginEntries?: PluginOverlayEntry[];
  settings: ModelSettings;
}

export function buildOverlayYaml(options: OverlayOptions): string {
  const { settings } = options;
  const entries: PluginOverlayEntry[] =
    options.pluginEntries && options.pluginEntries.length > 0
      ? options.pluginEntries
      : options.pluginEntryPath
        ? [{ id: "diandian-reading-browser", entryPath: options.pluginEntryPath }]
        : [];

  const existingPlugins = entries.filter((e) => fs.existsSync(e.entryPath));

  const lines: string[] = [
    "# Auto-generated by diandianreading v2",
    `- id: system-prompt`,
    `  config:`,
    `    personaPrefix: ${JSON.stringify(READING_PERSONA)}`,
    ``,
    `- id: llm-pi-ai`,
    `  config:`,
    `    providers:`,
    `      ${ROUTE_PROVIDER_ID}:`,
    `        displayName: ${JSON.stringify(settings.provider === "deepseek" ? "DeepSeek API" : "OpenAI Compatible")}`,
    `        api: openai-completions`,
    `        apiKeyEnv: DIANDIAN_LLM_API_KEY`,
    `        baseURL: ${JSON.stringify(settings.baseUrl)}`,
    `        models:`,
    `          - id: ${JSON.stringify(settings.model)}`,
    `            name: ${JSON.stringify(settings.model)}`,
    ``,
    `- id: agent-default-model`,
    `  config:`,
    `    provider: ${JSON.stringify(ROUTE_PROVIDER_ID)}`,
    `    model: ${JSON.stringify(settings.model)}`,
    ``,
    ...DISABLED_HARNESS_PLUGINS.flatMap((id) => [`- id: ${id}`, `  disabled: true`, ``]),
    ...READ_ONLY_FS_PATCH,
    `- id: spill-local`,
    `  config:`,
    `    root: ${JSON.stringify(harnessSpillDir(options.dshHome))}`,
    ``,
  ];

  const searchEndpoint = webSearchEndpoint(settings);
  if (searchEndpoint) {
    lines.push(
      `- id: web-deepseek-api`,
      `  config:`,
      `    searchBaseURL: ${JSON.stringify(searchEndpoint)}`,
      `    searchApiKeyEnv: DIANDIAN_LLM_API_KEY`,
      ``,
    );
  }

  if (existingPlugins.length > 0) {
    lines.push(`- insert:`);
    for (const plugin of existingPlugins) {
      lines.push(`    - id: ${plugin.id}`, `      name: ${JSON.stringify(plugin.entryPath)}`);
    }
    lines.push(``);
  }

  return lines.join("\n");
}

export function writeOverlayPatch(options: OverlayOptions): string {
  fs.mkdirSync(options.dshHome, { recursive: true, mode: 0o700 });
  const overlayPath = path.join(options.dshHome, "diandian.cordis.patch.yml");
  const content = buildOverlayYaml(options);
  const tempPath = `${overlayPath}.${process.pid}.${Date.now()}.tmp`;
  fs.writeFileSync(tempPath, content, { encoding: "utf8", mode: 0o600 });
  fs.renameSync(tempPath, overlayPath);
  return overlayPath;
}
